// Keep MAIN-world resources distinct from ISOLATED-world resources.
// Chrome can track an injected content-script file by its URL across declarations.
// Bundle the page observer so protocol.js is injected only into ISOLATED world.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const files = ['scripts/testcase/protocol.js', 'scripts/testcase/bridge.js'];
const bundle = '// Generated by node scripts/build-testcase-bridge.js. Edit protocol.js / bridge.js instead.\n' +
  files.map(file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n').trimEnd()).join('\n\n') + '\n';
fs.writeFileSync(path.join(root, 'scripts/testcase/page-bridge.js'), bundle);
